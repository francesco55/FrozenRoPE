def default_ruler_root() -> Path:
    """RULER checkout: $POSEXT_RULER_ROOT, else ./third_party/RULER (gitignored)."""
    return Path(os.environ.get("POSEXT_RULER_ROOT", "third_party/RULER"))


def default_data_root(tokenizer: str) -> Path:
    """Generated RULER data lives in the data cache, one tree per tokenizer."""
    cache = Path(os.environ.get("POSEXT_DATA_CACHE", "data_cache"))
    return cache / "ruler" / tokenizer.replace("/", "--")


def data_file(data_root: Path, length: int, task: str, split: str) -> Path:
    """RULER's own layout: <save_dir>/<task>/<subset>.jsonl, with save_dir = data_root/<length>."""
    return Path(data_root) / str(length) / task / f"{split}.jsonl"


def _meta_path(path: Path) -> Path:
    return path.with_suffix(".meta.json")


def _pred_file(pred_dir: Path, length: int, task: str) -> Path:
    return Path(pred_dir) / str(length) / f"{task}.jsonl"


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    """Read a jsonl file. A truncated last line (job killed mid-write) is dropped with a warning."""
    rows: list[dict[str, Any]] = []
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    for i, line in enumerate(lines):
        if not line.strip():
            continue
        try:
            rows.append(json.loads(line))
        except json.JSONDecodeError:
            if i == len(lines) - 1:
                logger.warning("Dropping truncated last line of %s", path)
                continue
            raise
    return rows


def _read_json(path: Path) -> Any:
    return json.loads(Path(path).read_text()) if Path(path).exists() else None


def _write_json(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2))


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def _strip_truncated_tail(path: Path) -> None:
    """Remove a partial last line so appending continues on a clean line boundary."""
    data = path.read_bytes()
    if data and not data.endswith(b"\n"):
        path.write_bytes(data[: data.rfind(b"\n") + 1])


