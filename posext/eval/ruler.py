"""NVIDIA RULER (Hsieh et al., 2024, arXiv:2404.06654): RULER's data and scoring, our inference.

Four subcommands, meant for three different machines on SCC:

    # 1. login node (needs internet): clone RULER at RULER_COMMIT, essays, nltk data, tokenizer
    uv run python -m posext.eval.ruler setup
    # 2. CPU job: RULER's own scripts/data/prepare.py for every task x length; files are checked
    uv run python -m posext.eval.ruler prepare --split validation
    # 3. GPU job: greedy decoding with our model; resumable; writes the results JSON at the end
    uv run python -m posext.eval.ruler run --run outputs/rq1_learned_freq_head --split validation
    uv run python -m posext.eval.ruler run --pos-mode yarn --factor 4 --split test
    # 4. anywhere: re-score saved predictions (no model)
    uv run python -m posext.eval.ruler score --pred-dir outputs/ruler/<tag>/validation

What comes from RULER and what doesn't:
- Data: generated by RULER's scripts (pinned commit), `base` template (OLMo-2-1B is a base
  model), HF tokenizer of the model, no newline stripping, RULER's default task configs
  from `scripts/synthetic.yaml`. Validation and test use different seeds.
- Prompt: `input + answer_prefix`, exactly what RULER's `pred/call_api.py` sends.
- Generation: greedy, `tokens_to_generate` from RULER's task constants (128 for NIAH), no
  stop words (RULER's default). Batch size 1.
- Scoring: RULER's `postprocess_pred` and `string_match_all` / `string_match_part`
  (copied below), in percent, as in the paper.
- Inference is ours. The paper uses vLLM, which cannot run our patched attention; RULER's HF
  backend would need a full model export per run (it cannot express training-free modes),
  loads with `trust_remote_code` + FlashAttention-2 and silently falls back on failure, and
  its evaluation script imports NeMo. Running our own loaders keeps one code path with PPL
  and passkey.

Attribution: `postprocess_pred` (from `scripts/eval/evaluate.py`) and `string_match_all` /
`string_match_part` (from `scripts/eval/synthetic/constants.py`) are copied from NVIDIA RULER,
https://github.com/NVIDIA/RULER, Copyright (c) 2024 NVIDIA CORPORATION, Apache License 2.0.
RULER's own files are used from the checkout and not vendored into this repo.
"""

