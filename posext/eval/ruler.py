def _csv(s: str) -> tuple[str, ...]:
    return tuple(x for x in s.split(",") if x)


def _lengths(s: str) -> tuple[int, ...]:
    return tuple(int(x) for x in _csv(s))


def _tag(args: argparse.Namespace) -> str:
    if args.tag:
        return args.tag
    return args.run.name if args.run else args.pos_mode


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """CLI with subcommands setup / prepare / run / score."""
    from posext.eval.common import add_model_args

    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    def common(sp: argparse.ArgumentParser, *, data: bool = True) -> None:
        sp.add_argument("--ruler-root", type=Path, default=None, help="default $POSEXT_RULER_ROOT or third_party/RULER")
        sp.add_argument("--tokenizer", default=DEFAULT_MODEL)
        if data:
            sp.add_argument("--data-root", type=Path, default=None, help="default $POSEXT_DATA_CACHE/ruler/<tokenizer>")
            sp.add_argument("--tasks", default=",".join(DEFAULT_TASKS))
            sp.add_argument("--lengths", default=",".join(map(str, DEFAULT_LENGTHS)))
            sp.add_argument("--split", default="validation", choices=sorted(SPLIT_SEEDS))

    common(sub.add_parser("setup", help="clone RULER, download essays/nltk/tokenizer (internet)"), data=False)

    sp = sub.add_parser("prepare", help="generate RULER data with RULER's prepare.py (CPU)")
    common(sp)
    sp.add_argument("--num-samples", type=int, default=None, help="default 100 validation / 500 test")
    sp.add_argument("--force", action="store_true", help="regenerate even if files match")
    sp.add_argument("--allow-unpinned", action="store_true")

    sp = sub.add_parser("run", help="predict with our model, then score (GPU)")
    common(sp)
    add_model_args(sp)
    sp.add_argument("--tag", default=None, help="name for outputs; default run dir name or pos mode")
    sp.add_argument("--pred-dir", type=Path, default=None, help="default outputs/ruler/<tag>/<split>")
    sp.add_argument("--max-samples", type=int, default=None, help="first N samples per file (debug)")
    sp.add_argument("--overwrite", action="store_true")
    sp.add_argument("--out", type=Path, default=None, help="default results/ruler_<tag>_<split>.json")

    sp = sub.add_parser("score", help="score saved predictions")
    sp.add_argument("--pred-dir", type=Path, required=True)
    sp.add_argument("--tasks", default=",".join(DEFAULT_TASKS))
    sp.add_argument("--lengths", default=",".join(map(str, DEFAULT_LENGTHS)))
    sp.add_argument("--out", type=Path, default=None)
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> None:
    """Entry point."""
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    args = parse_args(argv)
    ruler_root = getattr(args, "ruler_root", None) or default_ruler_root()

    if args.cmd == "setup":
        setup_ruler(ruler_root, tokenizer=args.tokenizer)
        return

    if args.cmd == "score":
        results = score_ruler(args.pred_dir, tasks=_csv(args.tasks), lengths=_lengths(args.lengths))
        results["pred_dir"] = str(args.pred_dir)
    else:
        data_root = args.data_root or default_data_root(args.tokenizer)
        tasks, lengths = _csv(args.tasks), _lengths(args.lengths)
        if args.cmd == "prepare":
            prepare_ruler(
                ruler_root=ruler_root, data_root=data_root, tasks=tasks, lengths=lengths,
                split=args.split, num_samples=args.num_samples, tokenizer=args.tokenizer,
                force=args.force, allow_unpinned=args.allow_unpinned,
            )
            return
        # run
        from transformers import AutoTokenizer

        from posext.eval.common import load_eval_model, model_source

        tag = _tag(args)
        pred_dir = args.pred_dir or Path("outputs") / "ruler" / tag / args.split
        tokenizer = AutoTokenizer.from_pretrained(args.tokenizer)
        model = load_eval_model(args)
        run_ruler(
            model, tokenizer, data_root=data_root, pred_dir=pred_dir, tasks=tasks,
            lengths=lengths, split=args.split, max_samples=args.max_samples,
            overwrite=args.overwrite,
        )
        results = score_ruler(pred_dir, tasks=tasks, lengths=lengths)
        results.update(
            {"tag": tag, "source": model_source(args), "pred_dir": str(pred_dir),
             "max_samples": args.max_samples}
        )
        args.out = args.out or Path("results") / f"ruler_{tag}_{args.split}.json"

    text = json.dumps(results, indent=2)
    print(text)
    if args.out:
        _write_json(args.out, results)
        logger.info("Wrote %s", args.out)


if __name__ == "__main__":
    main()
