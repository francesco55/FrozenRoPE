# Data generation (RULER's prepare.py) and checks.


def validate_samples(rows: list[dict[str, Any]], *, num_samples: int, length: int, path: Path) -> None:
    """Check a generated RULER file: count, fields, and that prompt + generation fits `length`."""
    if len(rows) != num_samples:
        raise RuntimeError(f"{path}: {len(rows)} samples, expected {num_samples}")
    for i, row in enumerate(rows):
        for key in ("index", "input", "outputs", "length"):
            if key not in row:
                raise RuntimeError(f"{path}: sample {i} has no {key!r}")
        if row["index"] != i:
            raise RuntimeError(f"{path}: sample {i} has index {row['index']}")
        if not row["outputs"] or not all(isinstance(o, str) and o for o in row["outputs"]):
            raise RuntimeError(f"{path}: sample {i} has empty references")
        if row["length"] > length:
            raise RuntimeError(f"{path}: sample {i} is {row['length']} tokens > {length}")


def _data_meta(
    *, commit: str, task: str, length: int, split: str, num_samples: int, tokenizer: str,
    spec: dict[str, Any],
) -> dict[str, Any]:
    return {
        "ruler_commit": commit,
        "task": task,
        "base_task": spec["base_task"],
        "task_args": spec["args"],
        "tokens_to_generate": spec["tokens_to_generate"],
        "length": length,
        "split": split,
        "seed": SPLIT_SEEDS[split],
        "num_samples": num_samples,
        "tokenizer": tokenizer,
        "model_template_type": MODEL_TEMPLATE,
    }


def prepare_ruler(
    *,
    ruler_root: Path,
    data_root: Path,
    tasks: Iterable[str] = DEFAULT_TASKS,
    lengths: Iterable[int] = DEFAULT_LENGTHS,
    split: str = "validation",
    num_samples: int | None = None,
    tokenizer: str = DEFAULT_MODEL,
    force: bool = False,
    allow_unpinned: bool = False,
    require_nltk: bool = True,
) -> list[Path]:
    """Generate RULER data with RULER's prepare.py; skip files that already match. Returns paths."""
    if split not in SPLIT_SEEDS:
        raise ValueError(f"split must be one of {sorted(SPLIT_SEEDS)}")
    num_samples = num_samples or DEFAULT_NUM_SAMPLES[split]
    tasks, lengths = tuple(tasks), tuple(lengths)
    commit = check_ruler_root(ruler_root, allow_unpinned=allow_unpinned)
    specs = task_specs(ruler_root, tasks)
    needs_essays = any(s["args"].get("type_haystack") == "essay" for s in specs.values())
    if needs_essays and not _essay_file(ruler_root).is_file():
        raise FileNotFoundError(f"{_essay_file(ruler_root)} missing; run `setup` first")
    if require_nltk:
        _check_nltk()

    # prepare.py starts each task script with a bare `python`: make that resolve to this venv.
    env = os.environ.copy()
    env["PATH"] = str(Path(sys.executable).parent) + os.pathsep + env.get("PATH", "")
    scripts_data = Path(ruler_root).resolve() / "scripts" / "data"

    paths = []
    for length in lengths:
        for task in tasks:
            path = data_file(data_root, length, task, split)
            meta = _data_meta(
                commit=commit, task=task, length=length, split=split,
                num_samples=num_samples, tokenizer=tokenizer, spec=specs[task],
            )
            if not force and path.is_file() and _read_json(_meta_path(path)) == meta:
                logger.info("RULER data up to date: %s", path)
                paths.append(path)
                continue
            # prepare.py skips any existing file with the right line count, even if it was made
            # with another seed or commit, so remove stale files first.
            path.unlink(missing_ok=True)
            _meta_path(path).unlink(missing_ok=True)
            cmd = [
                sys.executable, str(scripts_data / "prepare.py"),
                "--save_dir", str(Path(data_root).resolve() / str(length)),
                "--benchmark", "synthetic",
                "--task", task,
                "--subset", split,
                "--tokenizer_path", tokenizer,
                "--tokenizer_type", TOKENIZER_TYPE,
                "--max_seq_length", str(length),
                "--model_template_type", MODEL_TEMPLATE,
                "--num_samples", str(num_samples),
                "--random_seed", str(SPLIT_SEEDS[split]),
            ]  # fmt: skip
            logger.info("Generating %s @ %d (%s, %d samples) ...", task, length, split, num_samples)
            t0 = time.time()
            res = subprocess.run(
                cmd, cwd=scripts_data, env=env, capture_output=True, text=True, check=False
            )
            # prepare.py catches its task script's failure and only prints it: check the output.
            if res.returncode != 0 or not path.is_file():
                tail = "\n".join((res.stdout + "\n" + res.stderr).strip().splitlines()[-30:])
                raise RuntimeError(f"RULER prepare failed for {task} @ {length}:\n{tail}")
            validate_samples(read_jsonl(path), num_samples=num_samples, length=length, path=path)
            _write_json(_meta_path(path), meta)
            logger.info("  wrote %s (%.0f s)", path, time.time() - t0)
            paths.append(path)
    return paths


def load_ruler_data(
    data_root: Path, task: str, length: int, split: str
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Samples + metadata of a prepared file; fails if it is missing or from the wrong seed."""
    path = data_file(data_root, length, task, split)
    meta = _read_json(_meta_path(path))
    if not path.is_file() or meta is None:
        raise FileNotFoundError(
            f"No RULER data at {path}. Run: python -m posext.eval.ruler prepare --split {split}"
        )
    if meta["seed"] != SPLIT_SEEDS[split] or meta["split"] != split or meta["length"] != length:
        raise RuntimeError(f"{path} metadata does not match split={split} length={length}: {meta}")
    rows = read_jsonl(path)
    validate_samples(rows, num_samples=meta["num_samples"], length=length, path=path)
    return rows, {**meta, "data_sha256": _sha256(path)}


