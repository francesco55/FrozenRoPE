def ruler_commit(ruler_root: Path) -> str:
    """HEAD commit of the RULER checkout, or 'unknown' if it is not a git checkout."""
    try:
        out = subprocess.run(
            ["git", "-C", str(ruler_root), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "unknown"
    return out.stdout.strip()


def check_ruler_root(ruler_root: Path, *, allow_unpinned: bool = False) -> str:
    """Fail with setup instructions if RULER is missing or not at RULER_COMMIT. Returns the commit."""
    ruler_root = Path(ruler_root)
    if not (ruler_root / "scripts" / "data" / "prepare.py").is_file():
        raise FileNotFoundError(
            f"RULER not found at {ruler_root}. On a machine with internet run:\n"
            "  uv run python -m posext.eval.ruler setup"
            + (f" --ruler-root {ruler_root}" if ruler_root != default_ruler_root() else "")
        )
    commit = ruler_commit(ruler_root)
    if commit != RULER_COMMIT and not allow_unpinned:
        raise RuntimeError(
            f"RULER at {ruler_root} is at {commit}, expected pinned {RULER_COMMIT}. "
            "Re-run `setup`, or pass --allow-unpinned (the commit is recorded either way)."
        )
    return commit


def task_specs(ruler_root: Path, tasks: Iterable[str]) -> dict[str, dict[str, Any]]:
    """Per task: RULER base task, generation budget and complexity args, read from RULER itself."""
    scripts = Path(ruler_root) / "scripts"
    customized = yaml.safe_load((scripts / "synthetic.yaml").read_text())
    base = runpy.run_path(str(scripts / "data" / "synthetic" / "constants.py"))["TASKS"]
    specs: dict[str, dict[str, Any]] = {}
    for task in tasks:
        if task not in customized:
            raise ValueError(f"Unknown RULER task {task!r}; known: {sorted(customized)}")
        base_task = customized[task]["task"]
        if base_task not in METRICS:
            raise ValueError(f"No metric for RULER base task {base_task!r}")
        specs[task] = {
            "base_task": base_task,
            "tokens_to_generate": int(base[base_task]["tokens_to_generate"]),
            "args": dict(customized[task].get("args", {})),
        }
    return specs


def _essay_file(ruler_root: Path) -> Path:
    return Path(ruler_root) / "scripts" / "data" / "synthetic" / "json" / "PaulGrahamEssays.json"


def _check_nltk() -> None:
    """RULER needs punkt / punkt_tab; prepare.py would otherwise try to download them mid-job."""
    import nltk

    for res in ("tokenizers/punkt", "tokenizers/punkt_tab"):
        try:
            nltk.data.find(res)
        except LookupError as exc:
            raise RuntimeError(
                f"nltk resource {res} missing (NLTK_DATA={os.environ.get('NLTK_DATA')}). "
                "Run `python -m posext.eval.ruler setup` on a machine with internet."
            ) from exc


def setup_ruler(
    ruler_root: Path, *, tokenizer: str = DEFAULT_MODEL, commit: str = RULER_COMMIT
) -> None:
    """Everything that needs internet: RULER checkout, essays, nltk data, tokenizer files."""
    ruler_root = Path(ruler_root)
    if not (ruler_root / ".git").exists():
        ruler_root.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "clone", "--quiet", RULER_REPO, str(ruler_root)], check=True)
    if ruler_commit(ruler_root) != commit:
        subprocess.run(["git", "-C", str(ruler_root), "fetch", "--quiet", "origin"], check=True)
        subprocess.run(["git", "-C", str(ruler_root), "checkout", "--quiet", commit], check=True)
    logger.info("RULER at %s, commit %s", ruler_root, ruler_commit(ruler_root))

    essays = _essay_file(ruler_root)
    if not essays.is_file():
        logger.info("Downloading Paul Graham essays (NIAH haystack) ...")
        json_dir = essays.parent
        subprocess.run(
            [sys.executable, "download_paulgraham_essay.py"], cwd=json_dir, check=True
        )
        for tmp in ("essay_repo", "essay_html"):
            shutil.rmtree(json_dir / tmp, ignore_errors=True)
    n_chars = len(json.loads(essays.read_text())["text"])
    if n_chars < 100_000:
        raise RuntimeError(f"{essays} has only {n_chars} characters; essay download failed")
    logger.info("Essays: %s (%d characters)", essays, n_chars)

    import nltk

    download_dir = os.environ.get("NLTK_DATA")
    for pkg in ("punkt", "punkt_tab"):
        if not nltk.download(pkg, download_dir=download_dir, quiet=True):
            raise RuntimeError(f"nltk.download({pkg!r}) failed")
    _check_nltk()

    from transformers import AutoTokenizer

    AutoTokenizer.from_pretrained(tokenizer)  # populate the HF cache for offline jobs
    logger.info("Setup done. Next: `python -m posext.eval.ruler prepare --split validation`")


