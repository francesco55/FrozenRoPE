# Inference and scoring.


def run_ruler(
    model,
    tokenizer,
    *,
    data_root: Path,
    pred_dir: Path,
    tasks: Iterable[str] = DEFAULT_TASKS,
    lengths: Iterable[int] = DEFAULT_LENGTHS,
    split: str = "validation",
    max_samples: int | None = None,
    overwrite: bool = False,
) -> None:
    """Greedy-decode every prepared sample; one prediction jsonl per (length, task).

    Resumable: samples already in a prediction file are skipped, so a job that hits its wall
    time can simply be resubmitted. A prediction file made from different data is an error
    unless `overwrite`.
    """
    from posext.eval.common import greedy_generate

    model.eval()
    for length in lengths:
        for task in tasks:
            rows, meta = load_ruler_data(data_root, task, length, split)
            if max_samples is not None:
                rows = rows[:max_samples]
            pred_meta = {**meta, "n_expected": len(rows)}
            pf = _pred_file(pred_dir, length, task)
            pf.parent.mkdir(parents=True, exist_ok=True)
            old_meta = _read_json(_meta_path(pf))
            if pf.exists() and old_meta != pred_meta:
                if not overwrite:
                    raise RuntimeError(
                        f"{pf} was made from different data or settings; pass --overwrite "
                        f"or use another --pred-dir.\n  old: {old_meta}\n  new: {pred_meta}"
                    )
                pf.unlink()
            _write_json(_meta_path(pf), pred_meta)
            done: set[int] = set()
            if pf.exists():
                _strip_truncated_tail(pf)
                done = {r["index"] for r in read_jsonl(pf)}
            todo = [r for r in rows if r["index"] not in done]
            logger.info("RULER %s @ %d: %d done, %d to go", task, length, len(done), len(todo))
            metric = METRICS[meta["base_task"]]
            t0 = time.time()
            with open(pf, "a", encoding="utf-8", buffering=1) as fout:
                for i, row in enumerate(todo):
                    prompt = row["input"] + row.get("answer_prefix", "")
                    ids = tokenizer(prompt)["input_ids"]
                    if len(ids) + meta["tokens_to_generate"] > length:
                        logger.warning(
                            "%s #%d: %d prompt tokens + %d > %d", task, row["index"], len(ids),
                            meta["tokens_to_generate"], length,
                        )
                    new = greedy_generate(
                        model, ids, max_new_tokens=meta["tokens_to_generate"],
                        pad_token_id=tokenizer.eos_token_id,
                    )
                    pred = tokenizer.decode(new, skip_special_tokens=True)
                    rec = {
                        "index": row["index"],
                        "pred": pred,
                        "outputs": row["outputs"],
                        "length": row["length"],
                        "prompt_tokens": len(ids),
                        "score": metric([postprocess_pred(pred)], [row["outputs"]]),
                    }
                    fout.write(json.dumps(rec) + "\n")
                    if (i + 1) % 10 == 0 or i + 1 == len(todo):
                        rate = (time.time() - t0) / (i + 1)
                        logger.info(
                            "  %s @ %d: %d/%d  %.1f s/sample  ETA %.0f min", task, length,
                            i + 1, len(todo), rate, rate * (len(todo) - i - 1) / 60,
                        )


def score_ruler(
    pred_dir: Path,
    *,
    tasks: Iterable[str] = DEFAULT_TASKS,
    lengths: Iterable[int] = DEFAULT_LENGTHS,
) -> dict[str, Any]:
    """RULER scores per task and length (percent), averages over tasks, completeness flags."""
    tasks, lengths = tuple(tasks), tuple(lengths)
    scores: dict[str, dict[str, float]] = {}
    counts: dict[str, dict[str, int]] = {}
    nulls: dict[str, dict[str, int]] = {}
    complete = True
    metas = []
    for length in lengths:
        L = str(length)
        scores[L], counts[L], nulls[L] = {}, {}, {}
        for task in tasks:
            pf = _pred_file(pred_dir, length, task)
            meta = _read_json(_meta_path(pf))
            if meta is None or not pf.exists():
                logger.warning("No predictions for %s @ %d in %s", task, length, pred_dir)
                complete = False
                continue
            metas.append(meta)
            by_index = {r["index"]: r for r in read_jsonl(pf)}  # dedupe on index
            rows = [by_index[i] for i in sorted(by_index)]
            if len(rows) < meta["n_expected"]:
                complete = False
            if not rows:
                continue
            preds = [postprocess_pred(r["pred"]) for r in rows]
            scores[L][task] = METRICS[meta["base_task"]](preds, [r["outputs"] for r in rows])
            counts[L][task] = len(rows)
            nulls[L][task] = sum(len(p) == 0 for p in preds)
    avg_by_length = {
        L: round(sum(s.values()) / len(s), 2) for L, s in scores.items() if len(s) == len(tasks)
    }
    commits = sorted({m["ruler_commit"] for m in metas})
    splits = sorted({m["split"] for m in metas})
    return {
        "benchmark": "ruler",
        "ruler_commit": commits[0] if len(commits) == 1 else commits,
        "split": splits[0] if len(splits) == 1 else splits,
        "seed": sorted({m["seed"] for m in metas}),
        "tokenizer": sorted({m["tokenizer"] for m in metas}),
        "tasks": list(tasks),
        "lengths": list(lengths),
        "scores": scores,
        "avg_by_length": avg_by_length,
        "avg": (
            round(sum(avg_by_length.values()) / len(avg_by_length), 2)
            if len(avg_by_length) == len(lengths)
            else None
        ),
        "n": counts,
        "nulls": nulls,
        "complete": complete,
    }


