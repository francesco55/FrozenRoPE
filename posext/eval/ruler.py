# Scoring, copied from NVIDIA RULER (Apache-2.0; see module docstring).


def postprocess_pred(predict_str: str) -> str:
    """RULER's prediction cleanup: strip, and turn control characters into newlines."""
    predict_str = predict_str.strip()
    np_pattern = re.compile(r"[\x00-\x1f]")
    return np_pattern.sub("\n", predict_str).strip()


def string_match_part(preds: list[str], refs: list[list[str]]) -> float:
    """Percent of samples where any reference occurs in the prediction (case-insensitive)."""
    score = (
        sum(max(1.0 if r.lower() in pred.lower() else 0.0 for r in ref) for pred, ref in zip(preds, refs))
        / len(preds)
        * 100
    )
    return round(score, 2)


def string_match_all(preds: list[str], refs: list[list[str]]) -> float:
    """Mean over samples of the fraction of references found in the prediction, in percent."""
    score = (
        sum(
            sum(1.0 if r.lower() in pred.lower() else 0.0 for r in ref) / len(ref)
            for pred, ref in zip(preds, refs)
        )
        / len(preds)
        * 100
    )
    return round(score, 2)


METRICS: dict[str, Callable[[list[str], list[list[str]]], float]] = {
    "niah": string_match_all,
    "variable_tracking": string_match_all,
    "common_words_extraction": string_match_all,
    "freq_words_extraction": string_match_all,
    "qa": string_match_part,
}

